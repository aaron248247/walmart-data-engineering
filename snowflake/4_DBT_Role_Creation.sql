USE ROLE ACCOUNTADMIN;

-- Create dedicated role
CREATE ROLE IF NOT EXISTS WALMART_DBT_ROLE;

-- Grant warehouse access
GRANT USAGE ON WAREHOUSE WALMART_WH
TO ROLE WALMART_DBT_ROLE;

-- Grant database access
GRANT USAGE ON DATABASE WALMART_ANALYTICS
TO ROLE WALMART_DBT_ROLE;

-- Grant RAW schema access
GRANT USAGE ON SCHEMA WALMART_ANALYTICS.RAW
TO ROLE WALMART_DBT_ROLE;

-- Grant read access to current RAW tables
GRANT SELECT ON ALL TABLES
IN SCHEMA WALMART_ANALYTICS.RAW
TO ROLE WALMART_DBT_ROLE;

-- Grant read access to future RAW tables
GRANT SELECT ON FUTURE TABLES
IN SCHEMA WALMART_ANALYTICS.RAW
TO ROLE WALMART_DBT_ROLE;

-- Create an isolated development schema
CREATE SCHEMA IF NOT EXISTS WALMART_ANALYTICS.DBT_DEV;


GRANT USAGE, CREATE TABLE, CREATE VIEW
ON SCHEMA WALMART_ANALYTICS.DBT_DEV
TO ROLE WALMART_DBT_ROLE;



-- Final transformation schemas
GRANT USAGE, CREATE TABLE, CREATE VIEW
ON SCHEMA WALMART_ANALYTICS.STAGING
TO ROLE WALMART_DBT_ROLE;

GRANT USAGE, CREATE TABLE, CREATE VIEW
ON SCHEMA WALMART_ANALYTICS.MARTS
TO ROLE WALMART_DBT_ROLE;


