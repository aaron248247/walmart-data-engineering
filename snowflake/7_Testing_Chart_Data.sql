USE WAREHOUSE WALMART_WH;
USE DATABASE WALMART_ANALYTICS;
USE SCHEMA MARTS;


SELECT TOP 10 * FROM WALMART_ANALYTICS.MARTS.WALMART_STORE_DIM;

SELECT TOP 10 * FROM WALMART_ANALYTICS.MARTS.WALMART_DATE_DIM;

SELECT TOP 10 * FROM WALMART_ANALYTICS.MARTS.WALMART_FACT_TABLE;



SET START_DATE = '2010-02-05'::DATE;
SET END_DATE   = '2013-12-31'::DATE;

SELECT DISTINCT WFT.STORE_ID, WDD.ISHOLIDAY, SUM(WFT.STORE_WEEKLY_SALES) AS WEEKLY_SALES FROM WALMART_ANALYTICS.MARTS.WALMART_FACT_TABLE WFT
INNER JOIN WALMART_ANALYTICS.MARTS.WALMART_DATE_DIM WDD
ON WFT.DATE_ID = WDD.DATE_ID
WHERE WFT.VRSN_END_DATE IS NULL
AND WDD.STORE_DATE BETWEEN $START_DATE AND $END_DATE
GROUP BY WFT.STORE_ID, WDD.ISHOLIDAY
ORDER BY STORE_ID, ISHOLIDAY 
;


